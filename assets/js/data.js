/* ------------------------------------------------------ 给 LLM 的规则摘要 */
function buildRuleDigest() {
  const lines = [];
  lines.push('【八类特殊作业票 · 官方填写标准摘要】');
  PERMITS.forEach(p => {
    lines.push('');
    lines.push('### ' + p.name + '（' + p.code + '）');
    lines.push('适用：' + p.when);
    lines.push('分级：' + p.levels.map(l => l.name + (l.desc ? '（' + l.desc.replace(/<br>/g, '；') + '）' : '')).join('；'));
    lines.push('风险辨识必选项：' + p.risks.must.join('、') + '；条件项：' + p.risks.cond.join('、'));
    const musts = p.measures.filter(m => m.must);
    lines.push('必须勾选（' + musts.length + '条，无条件条目，票面一律打√。其中带"为什么勾"的是现场核实型：勾√ 表示已核实并确认现场处于该状态，核实结果为"没有"也照样打√，不要建议用户标注不适用）：' + musts.map(m => '措施' + m.no + ' ' + m.text + (m.why ? '〔为什么勾：' + m.why + '〕' : '') + '〔确认人：' + m.by + '〕').join(' ｜ '));
    const conds = p.measures.filter(m => !m.must && m.cond).map(m => '措施' + m.no + '(' + m.cond + (m.cross ? '；关联票联动：' + m.cross.map(x => x === '*' ? '涉及任一其他作业票' : (PERMIT_MAP[x] ? PERMIT_MAP[x].short : x) + '票').join('、') : '') + '，确认人：' + m.by + ')');
    if (conds.length) lines.push('核查确认（' + conds.length + '条，方框先留空，不能由工具替用户判"不涉及"：按括号里的条件逐条核实，涉及的打√，确实不涉及的在备注写明理由后再标"不适用"；只有带"关联票联动"的条目，在用户没勾那张票时才可判为明确不涉及）：' + conds.join(' ｜ '));
    lines.push('高频错误：' + p.errors.map(e => (e.kind === 'onsite' ? '〔现场落实，非票面错误〕' : '') + e.title + '——' + e.detail).join(' ｜ '));
    lines.push('签字链：' + p.approvals.map(a => a.role + '=' + a.who.replace(/<br>/g, '/')).join('；'));
  });
  lines.push('');
  lines.push('【跨票证通用红线】标〔现场落实〕的条目只指三类：现场没实际做措施（如没铺接火毯、没摆灭火器、没加盲板）、人员定位卡没戴、监控点位没对准作业面。这类要看照片与现场证据判断，不要只凭票面。凡是"该不该勾、勾没勾、签没签、填没填"的问题都属票面，不在此列。');
  GLOBAL_ERRORS.forEach((e, i) => lines.push((i + 1) + '. ' + (e.kind === 'onsite' ? '〔现场落实〕' : '') + e.title + '：' + e.detail + '（适用：' + e.scope + '）'));

  lines.push('');
  lines.push('【交叉作业联动规则：现场同时涉及两类及以上作业时，每类作业票都要单独办票，各自的风险辨识与安全措施都要独立勾选，另需按下表补勾】');
  [
    ['hot', 'height'], ['hot', 'confined'], ['hot', 'elec'],
    ['confined', 'height'], ['dig', 'confined'], ['lift', 'traffic'], ['blind', 'hot']
  ].forEach(([main, rel]) => {
    const m = PERMIT_MAP[main], r = PERMIT_MAP[rel];
    const c = (r.cross && r.cross[main]) || {};
    const seg = [];
    if (c.add && c.add.length) seg.push(r.short + '票加勾措施' + c.add.join('、'));
    if (r.relNo) seg.push(r.short + '票须勾"其他相关特殊作业已办理相应安全作业票"（措施' + r.relNo + '）');
    if (c.risk && c.risk.length) seg.push(r.short + '票补辨识：' + c.risk.join('、'));
    if (c.mainRisk && c.mainRisk.length) seg.push(m.short + '票补辨识：' + c.mainRisk.join('、'));
    if (c.note) seg.push('现场提示：' + c.note);
    lines.push('· ' + m.name + ' × ' + r.name + '：' + seg.join('；'));
  });

  return lines.join('\n');
}
